export interface GeminiReauditPromptParams {
  setName: string;
  masterTopicId: number;
  topicName: string;
  subjectName: string;
  questions: any[];
}

export function generateGeminiReauditPrompt({
  setName,
  masterTopicId,
  topicName,
  subjectName,
  questions,
}: GeminiReauditPromptParams): string {
  // Extract clean question objects with essential fields
  const formattedQuestions = questions.map((q, idx) => {
    const rawOpts = q.options || [];
    const options = rawOpts.map((o: any) => (typeof o === "string" ? o : o.text || ""));

    let answer = q.answer || q.correctAnswer || q.correctOption || "A";
    if (typeof answer === "number") {
      answer = ["A", "B", "C", "D"][answer] || "A";
    }

    return {
      index: idx + 1,
      id: q.id || q._id,
      type: q.type || "mcq",
      question: q.questionText || q.question || "",
      options,
      answer,
      explanation: q.explanation || "",
      meta: q.meta || undefined,
    };
  });

  return `आप राजस्थान प्रतियोगी परीक्षाओं (RPSC, RSMSSB, 2nd Grade, RAS) के मुख्य परीक्षा नियंत्रक एवं विषय विशेषज्ञ (Chief Examiner & Lead GK Question Setter) हैं।

यह सेट पूर्व में तैयार किया गया था, परंतु इसमें कुछ तकनीकी एवं तथ्यात्मक त्रुटियाँ (गलत उत्तर कुंजी, विकृत विकल्प, या अधूरी फॉर्मेटिंग) पाई गई हैं।
अतः इस सेट का **द्वितीय-चरण गहन पुनरीक्षण (Second-Pass Rigorous Re-Audit & Fix)** किया जाना अनिवार्य है।

================================================================================
सेट विवरण (SET DETAILS):
================================================================================
- विषय (Subject): ${subjectName}
- शीर्षक (Master Topic #${masterTopicId}): ${topicName}
- अभ्यास सेट (Practice Set): ${setName}
- कुल प्रश्न: ठीक 20 प्रश्न (Array Length = 20)

================================================================================
द्वितीय-चरण पुनरीक्षण के अनिवार्य कड़े मानक (STRICT RE-AUDIT RULES):
================================================================================

1. उत्तर कुंजी का सत्य सत्यापन (FACT-CHECK EVERY ANSWER - CRITICAL):
   - प्रत्येक प्रश्न के वर्तमान 'answer' की प्रामाणिक RPSC / NCERT / राजस्थान बोर्ड पाठ्यपुस्तकों के आधार पर पुनः जाँच करें।
   - यदि वर्तमान उत्तर गलत है, तो उसे तुरंत सही विकल्प इंडेक्स ('A', 'B', 'C', या 'D') में बदलें और व्याख्या में प्रमाणित कारण लिखें।
   - उत्तर वितरण को संतुलित रखें (A, B, C, D का समानुपातिक वितरण ~5 प्रत्येक)।

2. अक्षरों की अखंडता (ZERO LETTER STRIPPING RULE - ABSOLUTE MANDATE):
   - किसी भी शब्द का पहला अक्षर या मात्रा कटी हुई नहीं होनी चाहिए!
   - उदाहरण:
     * 'बांसवाड़ा' को 'ांसवाड़ा' नहीं, शुद्ध 'बांसवाड़ा' लिखें।
     * 'सीकर' को 'ीकर' नहीं, 'सीकर' लिखें।
     * 'दक्षिण' को 'क्षिण' नहीं, 'दक्षिण' लिखें।
     * 'अरब सागर' को 'रब सागर' नहीं, 'अरब सागर' लिखें।
     * '100 सेमी' को '00 सेमी' नहीं, '100 सेमी' लिखें।
   - विकल्पों के भीतर 'A.', 'B.', 'C.', 'D.' या 'अ.', 'ब.', 'स.', 'द.' जैसे अतिरिक्त उपसर्ग कतई न लिखें; केवल शुद्ध विकल्प पाठ लिखें।

3. सुमेलित प्रश्न (MATCH THE FOLLOWING RULES):
   - सूची-I के लिए छोटे अक्षर (a, b, c, d) तथा सूची-II के लिए रोमन अंक (I, II, III, IV) रखें।
   - चारों विकल्पों का प्रारूप अनिवार्य रूप से मानक रखें:
     'a-I, b-II, c-III, d-IV' या 'a-II, b-I, c-IV, d-III'
   - किसी भी विकल्प में से 'a-' नहीं छूटना चाहिए।
   - व्याख्या में वास्तविक जोड़ियों का स्पष्ट मिलान लिखें (जैसे 'झालावाड़ → अति-आर्द्र (I) | जैसलमेर → शुष्क (II)').
   - सुनिश्चित करें कि 'answer' उस विकल्प ('A', 'B', 'C', या 'D') को इंगित करता है जहाँ सही कूट स्थित है।

4. मूल पहचान (ID) की अखंडता:
   - प्रत्येक प्रश्न की मूल 'id' (उदा. 'rg_000394') को अक्षुण्ण रखें; इसे बिल्कुल न बदलें।

5. JSON उद्धरण सुरक्षा (QUOTE ESCAPING):
   - प्रश्न या विकल्प में उद्धृत शब्दों के लिए या तो एकल उद्धरण ('...') का प्रयोग करें अथवा उचित रूप से एस्केप (\\") करें ताकि JSON कभी क्रैश न हो।

================================================================================
पुनरीक्षण हेतु वर्तमान 20 प्रश्न (CURRENT 20 QUESTIONS TO RE-AUDIT):
================================================================================
${JSON.stringify(formattedQuestions, null, 2)}

================================================================================
अपेक्षित आउटपुट (STRICT JSON OUTPUT FORMAT):
================================================================================
केवल और केवल शुद्ध JSON Array वापस करें जिसमें सभी 20 सुधारे हुए प्रश्न ऑब्जेक्ट्स हों।
कोई अतिरिक्त वार्तालाप, प्रस्तावना या अतिरिक्त टेक्स्ट न जोड़ें:

[
  {
    "id": "${formattedQuestions[0]?.id || "rg_000001"}",
    "topic": "${topicName}",
    "masterTopicId": ${masterTopicId},
    "type": "mcq",
    "question": "शुद्ध प्रश्न पाठ...",
    "options": [
      "विकल्प 1",
      "विकल्प 2",
      "विकल्प 3",
      "विकल्प 4"
    ],
    "answer": "A",
    "explanation": "विस्तृत एवं सटीक प्रामाणिक व्याख्या..."
  }
  ... (ठीक 20 प्रश्न)
]`;
}

